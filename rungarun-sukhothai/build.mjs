// Bundles src/ (+ admin/) into dist/ and generates db/seed.sql from the JSON content.
//   node build.mjs          -> dist/index.html, dist/admin/index.html, dist/_headers, dist/_routes.json, db/seed.sql
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(new URL(import.meta.url).pathname);
const r = (...p) => path.join(root, ...p);
const read = (f) => fs.readFileSync(f, 'utf8');
const write = (f, t) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, t); };
const safeScript = (t) => t.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

// ---- content ----
const home = JSON.parse(read(r('src/data/home.json')));
const order = home.order;
const periods = {};
for (const k of order) periods[k] = JSON.parse(read(r('src/data', `${k}.json`)));
const homeDoc = { ...home }; // includes order
const data = { home: homeDoc, periods, order };
const config = JSON.parse(read(r('src/site.config.json')));

// ---- public site ----
const cssOrder = JSON.parse(read(r('src/styles/_order.json')));
const css = cssOrder.map((n) => read(r('src/styles', `${n}.css`))).join('\n');
let html = read(r('src/index.html'));
const partial = (name) => read(r('src/partials', `${name}.html`));
let body = partial('body').replace('<!--@partial svg-defs-->', partial('svg-defs'));
html = html
  .replace('/*@css*/', () => css)
  .replace('<!--@partial body-->', () => body)
  .replace('/*@config*/', () => JSON.stringify(config))
  .replace('/*@data*/', () => safeScript(JSON.stringify(data)))
  .replace('/*@js:art*/', () => safeScript(read(r('src/js/art.js'))))
  .replace('/*@js:content*/', () => safeScript(read(r('src/js/content.js'))))
  .replace('/*@js:app*/', () => safeScript(read(r('src/js/app.js'))));
write(r('dist/index.html'), html);

// ---- admin (separate page at /admin/) ----
let adm = read(r('admin/index.html'));
adm = adm
  .replace('/*@css*/', () => read(r('admin/admin.css')))
  .replace('/*@js:art*/', () => safeScript(read(r('src/js/art.js'))))
  .replace('/*@js*/', () => safeScript(read(r('admin/admin.js'))));
write(r('dist/admin/index.html'), adm);

// ---- Cloudflare Pages config ----
write(r('dist/_routes.json'), JSON.stringify({ version: 1, include: ['/api/*'], exclude: [] }, null, 2));
write(r('dist/_headers'), `/admin/*
  X-Robots-Tag: noindex, nofollow
  Cache-Control: no-store
  X-Frame-Options: DENY
  Referrer-Policy: same-origin
/*
  X-Content-Type-Options: nosniff
`);
write(r('dist/robots.txt'), 'User-agent: *\nDisallow: /admin/\nDisallow: /api/\n');

// ---- D1 seed ----
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const now = Date.now();
let sql = '-- generated by build.mjs from src/data/*.json. Safe to re-run: it overwrites the live content.\n';
for (const [key, doc] of Object.entries({ home: homeDoc, ...periods })) {
  sql += `INSERT INTO content (key, json, version, updated_at, updated_by) VALUES (${q(key)}, ${q(JSON.stringify(doc))}, 1, ${now}, 'seed')\n` +
    `  ON CONFLICT(key) DO UPDATE SET json=excluded.json, version=content.version+1, updated_at=excluded.updated_at, updated_by='seed';\n`;
}
write(r('db/seed.sql'), sql);

const kb = (f) => (fs.statSync(f).size / 1024).toFixed(0) + ' KB';
console.log(`dist/index.html ${kb(r('dist/index.html'))} | dist/admin/index.html ${kb(r('dist/admin/index.html'))} | db/seed.sql ${kb(r('db/seed.sql'))}`);
